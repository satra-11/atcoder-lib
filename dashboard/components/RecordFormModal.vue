<script setup lang="ts">
import { ref, watch, computed } from 'vue'
import type { ProblemRecord, DifficultyColor, SubmissionResult } from '~/types/record'
import { getDefaultDifficulty } from '~/lib/utils'
import DifficultyBadge from '~/components/DifficultyBadge.vue'
import ResultBadge from '~/components/ResultBadge.vue'

const props = defineProps<{
  open: boolean
  record?: ProblemRecord | null
  existingTags?: string[]
  existingRecords?: ProblemRecord[]
}>()

const emit = defineEmits<{
  (e: 'update:open', val: boolean): void
  (e: 'saved', record: ProblemRecord & { isOverwritten?: boolean }): void
}>()

const isOpen = computed({
  get: () => props.open,
  set: (val: boolean) => emit('update:open', val)
})

const isEdit = computed(() => Boolean(props.record?.id))
const title = computed(() => isEdit.value ? '正答記録を編集' : '新しい正答記録を追加')
const description = computed(() => isEdit.value ? '記録の内容やメモ、復習ステータスを更新します。' : '回数と問題を選ぶだけでURLと難易度色が自動設定されます。')

// コンテスト入力用
const contestType = ref<'ABC' | 'ARC' | 'AGC' | 'AHC' | 'OTHER'>('ABC')
const contestNumber = ref<string>('393')
const customContestName = ref<string>('')

// 問題選択用
const problemChoice = ref<string>('C')
const customProblem = ref<string>('')

// 難易度色の自動設定と手動カスタマイズ
const difficulty = ref<DifficultyColor>('brown')
const isCustomDifficulty = ref(false)

// 自動計算されるコンテスト名と問題記号
const contestDisplay = computed(() => {
  if (contestType.value === 'OTHER') {
    return customContestName.value.trim().toUpperCase()
  }
  return `${contestType.value}${contestNumber.value.trim()}`.toUpperCase()
})

const problemDisplay = computed(() => {
  if (problemChoice.value === 'OTHER') {
    return customProblem.value.trim().toUpperCase()
  }
  return problemChoice.value.trim().toUpperCase()
})

// 自動構築される問題URL
const url = ref('')
const isManualUrl = ref(false)

const autoGeneratedUrl = computed(() => {
  const c = contestDisplay.value.toLowerCase().replace(/\s+/g, '')
  const p = problemDisplay.value.toLowerCase().replace(/\s+/g, '')
  if (!c || !p) return ''
  return `https://atcoder.jp/contests/${c}/tasks/${c}_${p}`
})

// 一意なプライマリーキー（コンテスト種別＋番号＋問題記号）
const currentTargetId = computed(() => {
  const c = contestDisplay.value.trim().toLowerCase().replace(/\s+/g, '')
  const p = problemDisplay.value.trim().toLowerCase().replace(/\s+/g, '')
  if (!c || !p) return ''
  return `${c}_${p}`
})

// 新規作成時に同一キーが存在するか判定（重複検知）
const isDuplicate = computed(() => {
  if (isEdit.value) return false
  if (!props.existingRecords || !currentTargetId.value) return false
  return props.existingRecords.some(r => r.id === currentTargetId.value)
})

// 問題記号やコンテスト種別が変わった時：URLと難易度色を自動決定
watch([contestType, problemChoice, customProblem], () => {
  if (!isCustomDifficulty.value) {
    const prob = problemChoice.value === 'OTHER' ? customProblem.value : problemChoice.value
    difficulty.value = getDefaultDifficulty(contestType.value, prob)
  }
})

// URL自動更新
watch(autoGeneratedUrl, (newUrl) => {
  if (!isManualUrl.value) {
    url.value = newUrl
  }
}, { immediate: true })

// その他のフォーム状態
const result = ref<SubmissionResult>('AC')
const solvedAt = ref('')
const timeMinutes = ref<number | undefined>(undefined)
const tags = ref<string[]>([])
const tagInput = ref('')
const reviewNeeded = ref(false)
const memo = ref('')

const isSubmitting = ref(false)
const errorMsg = ref('')

const contestTypeOptions = [
  { label: 'ABC (Beginner)', value: 'ABC' },
  { label: 'ARC (Regular)', value: 'ARC' },
  { label: 'AGC (Grand)', value: 'AGC' },
  { label: 'AHC (Heuristic)', value: 'AHC' },
  { label: 'その他', value: 'OTHER' }
]

const problemOptions = ['A', 'B', 'C', 'D', 'E', 'F', 'G', 'Ex', 'OTHER']
const diffOptions: DifficultyColor[] = ['gray', 'brown', 'green', 'cyan', 'blue', 'yellow', 'orange', 'red']
const resultOptions: SubmissionResult[] = ['AC', '解説AC', 'WA', 'TLE', 'RE', 'MLE']

// モーダルオープン時または record 変更時にフォーム初期化
watch(
  () => props.open,
  (openVal) => {
    if (!openVal) return
    errorMsg.value = ''
    isManualUrl.value = false
    isCustomDifficulty.value = false

    if (props.record) {
      const contestMatch = (props.record.contest || '').match(/^([A-Za-z]+)(\d+)$/)
      if (contestMatch && ['ABC', 'ARC', 'AGC', 'AHC'].includes(contestMatch[1].toUpperCase())) {
        contestType.value = contestMatch[1].toUpperCase() as any
        contestNumber.value = contestMatch[2]
        customContestName.value = ''
      } else {
        contestType.value = 'OTHER'
        customContestName.value = props.record.contest || ''
        contestNumber.value = ''
      }

      const prob = (props.record.problem || '').toUpperCase()
      if (problemOptions.includes(prob)) {
        problemChoice.value = prob
        customProblem.value = ''
      } else {
        problemChoice.value = 'OTHER'
        customProblem.value = prob
      }

      url.value = props.record.url || autoGeneratedUrl.value
      if (props.record.url && props.record.url !== autoGeneratedUrl.value) {
        isManualUrl.value = true
      }

      difficulty.value = props.record.difficulty || getDefaultDifficulty(contestType.value, problemChoice.value)
      if (props.record.difficulty && props.record.difficulty !== getDefaultDifficulty(contestType.value, problemChoice.value)) {
        isCustomDifficulty.value = true
      }

      result.value = props.record.result
      solvedAt.value = props.record.solvedAt ? props.record.solvedAt.slice(0, 16) : new Date().toISOString().slice(0, 16)
      timeMinutes.value = props.record.timeMinutes ?? undefined
      tags.value = [...(props.record.tags || [])]
      reviewNeeded.value = props.record.reviewNeeded
      memo.value = props.record.memo || ''
    } else {
      contestType.value = 'ABC'
      if (!contestNumber.value) contestNumber.value = '393'
      problemChoice.value = 'C'
      customContestName.value = ''
      customProblem.value = ''
      url.value = autoGeneratedUrl.value
      difficulty.value = getDefaultDifficulty('ABC', 'C')
      isCustomDifficulty.value = false

      result.value = 'AC'
      const now = new Date()
      const offsetMs = now.getTimezoneOffset() * 60000
      const localISOTime = new Date(now.getTime() - offsetMs).toISOString().slice(0, 16)
      solvedAt.value = localISOTime
      timeMinutes.value = undefined
      tags.value = []
      tagInput.value = ''
      reviewNeeded.value = false
      memo.value = ''
    }
  },
  { immediate: true }
)

function addTag() {
  const val = tagInput.value.trim()
  if (val && !tags.value.includes(val)) {
    tags.value.push(val)
  }
  tagInput.value = ''
}

function removeTag(tagToRemove: string) {
  tags.value = tags.value.filter(t => t !== tagToRemove)
}

function selectExistingTag(tag: string) {
  if (!tags.value.includes(tag)) {
    tags.value.push(tag)
  }
}

async function onSubmit() {
  if (!contestDisplay.value.trim() || !problemDisplay.value.trim()) {
    errorMsg.value = 'コンテスト回数と問題を指定してください。'
    return
  }

  isSubmitting.value = true
  errorMsg.value = ''

  try {
    const payload = {
      contest: contestDisplay.value.trim(),
      problem: problemDisplay.value.trim(),
      url: url.value.trim() || autoGeneratedUrl.value,
      difficulty: difficulty.value,
      result: result.value,
      solvedAt: solvedAt.value ? new Date(solvedAt.value).toISOString() : new Date().toISOString(),
      timeMinutes: timeMinutes.value !== undefined && timeMinutes.value !== null && String(timeMinutes.value).trim() !== '' && !Number.isNaN(Number(timeMinutes.value))
        ? Number(timeMinutes.value)
        : null,
      tags: tags.value,
      reviewNeeded: reviewNeeded.value,
      memo: memo.value.trim()
    }

    let saved: ProblemRecord
    if (isEdit.value && props.record?.id) {
      saved = await $fetch<ProblemRecord>(`/api/records/${props.record.id}`, {
        method: 'PUT',
        body: payload
      })
    } else {
      saved = await $fetch<ProblemRecord>('/api/records', {
        method: 'POST',
        body: payload
      })
    }

    emit('saved', saved)
    isOpen.value = false
  } catch (err: any) {
    errorMsg.value = err?.data?.statusMessage || err?.message || '保存中にエラーが発生しました。'
  } finally {
    isSubmitting.value = false
  }
}
</script>

<template>
  <UModal v-model="isOpen" :ui="{ width: 'sm:max-w-xl' }">
    <UCard :ui="{ ring: '', divide: 'divide-y divide-border/50' }">
      <template #header>
        <div class="flex items-start justify-between">
          <div>
            <h3 class="text-base font-semibold leading-6 text-foreground">
              {{ title }}
            </h3>
            <p class="mt-1 text-xs text-muted-foreground">
              {{ description }}
            </p>
          </div>
          <UButton
            color="gray"
            variant="ghost"
            icon="i-lucide-x"
            class="-mr-1"
            @click="isOpen = false"
          />
        </div>
      </template>

      <form id="record-form" @submit.prevent="onSubmit" class="space-y-4 py-1">
        <!-- Error Message -->
        <UAlert
          v-if="errorMsg"
          color="red"
          variant="subtle"
          :title="errorMsg"
          icon="i-lucide-alert-circle"
        />

        <!-- Duplicate Notice (Upsert Info) -->
        <UAlert
          v-if="isDuplicate"
          color="amber"
          variant="subtle"
          icon="i-lucide-info"
          :title="`同一問題（${currentTargetId}）の記録が既に存在します`"
          description="このまま保存すると、既存の記録が最新の内容で上書き更新されます。"
        />

        <!-- Contest & Problem Picker Section -->
        <div class="p-3.5 rounded-xl border border-border/70 bg-muted/20 space-y-3">
          <div class="grid grid-cols-1 sm:grid-cols-2 gap-3 items-end">
            <!-- Contest Type -->
            <div>
              <label class="block text-xs font-semibold text-muted-foreground mb-1">種別</label>
              <USelect
                v-model="contestType"
                :options="contestTypeOptions"
                value-attribute="value"
                option-attribute="label"
                size="sm"
              />
            </div>

            <!-- Contest Number -->
            <div v-if="contestType !== 'OTHER'">
              <label class="block text-xs font-semibold text-muted-foreground mb-1">回数 (番号) *</label>
              <UInput
                v-model="contestNumber"
                placeholder="例: 393"
                required
                size="sm"
                class="font-mono"
              />
            </div>

            <!-- Other Contest Name -->
            <div v-else>
              <label class="block text-xs font-semibold text-muted-foreground mb-1">コンテスト名 *</label>
              <UInput
                v-model="customContestName"
                placeholder="例: typical90"
                required
                size="sm"
                class="font-mono"
              />
            </div>
          </div>

          <!-- Problem Picker (Card Style) -->
          <div class="space-y-2 pt-1 border-t border-border/40">
            <div class="flex items-center justify-between flex-wrap gap-2">
              <label class="block text-xs font-semibold text-muted-foreground">問題 *</label>
              <div class="flex items-center gap-1.5 shrink-0">
                <span class="text-[11px] text-muted-foreground">自動難易度:</span>
                <DifficultyBadge :difficulty="difficulty" />
                <UButton
                  color="gray"
                  variant="ghost"
                  size="2xs"
                  icon="i-lucide-palette"
                  title="難易度色を手動変更する"
                  @click="isCustomDifficulty = !isCustomDifficulty"
                />
              </div>
            </div>

            <div class="flex items-center gap-1.5 flex-wrap">
              <button
                v-for="p in problemOptions"
                :key="p"
                type="button"
                class="h-8 px-3 rounded-md text-xs font-mono font-semibold border transition-all cursor-pointer flex items-center justify-center shadow-xs"
                :class="problemChoice === p
                  ? 'bg-primary text-primary-foreground border-primary shadow-sm ring-2 ring-primary/20 font-bold'
                  : 'border-border/70 bg-background/60 hover:bg-muted text-foreground/85 hover:text-foreground'"
                @click="problemChoice = p"
              >
                {{ p === 'OTHER' ? 'その他' : p }}
              </button>
            </div>

            <!-- Custom Problem Input if OTHER -->
            <div v-if="problemChoice === 'OTHER'" class="pt-1 flex items-center gap-2">
              <label class="text-xs text-muted-foreground shrink-0 font-medium">問題記号/番号:</label>
              <UInput
                v-model="customProblem"
                placeholder="例: Ex, H, 001 など"
                class="font-mono uppercase w-40"
                size="sm"
                autofocus
              />
            </div>
          </div>

          <!-- Manual Difficulty Color Override -->
          <div v-if="isCustomDifficulty" class="p-2.5 rounded-lg border border-border/60 bg-background/60 space-y-1.5">
            <div class="flex items-center justify-between text-[11px] text-muted-foreground">
              <span>難易度色を手動で変更:</span>
              <button
                type="button"
                class="underline hover:text-foreground cursor-pointer"
                @click="isCustomDifficulty = false; difficulty = getDefaultDifficulty(contestType, problemChoice)"
              >
                自動判定に戻す
              </button>
            </div>
            <div class="grid grid-cols-4 sm:grid-cols-8 gap-1">
              <button
                v-for="d in diffOptions"
                :key="d"
                type="button"
                class="p-1 rounded-md text-xs font-medium border flex items-center justify-center transition-all cursor-pointer"
                :class="difficulty === d ? 'ring-2 ring-primary border-primary shadow-sm' : 'border-border/50 opacity-60 hover:opacity-100'"
                @click="difficulty = d"
              >
                <DifficultyBadge :difficulty="d" class="pointer-events-none scale-90" />
              </button>
            </div>
          </div>

          <!-- Auto Generated URL Preview -->
          <div class="pt-2 border-t border-border/50 text-xs flex items-center justify-between gap-2">
            <div class="flex items-center gap-1.5 min-w-0 flex-1">
              <UIcon name="i-lucide-sparkles" class="w-3.5 h-3.5 text-primary shrink-0" />
              <span class="text-muted-foreground shrink-0">URL:</span>
              <a
                v-if="url"
                :href="url"
                target="_blank"
                class="text-primary hover:underline font-mono truncate inline-flex items-center gap-1"
              >
                {{ url }}
                <UIcon name="i-lucide-external-link" class="w-3 h-3 shrink-0" />
              </a>
            </div>
            <button
              type="button"
              class="text-[11px] text-muted-foreground hover:text-foreground underline shrink-0 cursor-pointer"
              @click="isManualUrl = !isManualUrl"
            >
              {{ isManualUrl ? '自動に戻す' : '手動編集' }}
            </button>
          </div>

          <div v-if="isManualUrl">
            <UInput v-model="url" placeholder="https://atcoder.jp/contests/..." size="xs" class="font-mono" />
          </div>
        </div>

        <!-- Result & Time row -->
        <div class="grid grid-cols-1 sm:grid-cols-3 gap-3">
          <div class="sm:col-span-3">
            <label class="block text-xs font-medium text-muted-foreground mb-1.5">判定結果 *</label>
            <div class="flex flex-wrap gap-1.5">
              <button
                v-for="res in resultOptions"
                :key="res"
                type="button"
                class="px-2.5 py-1 rounded-md text-xs font-medium border transition-all cursor-pointer"
                :class="result === res ? 'ring-2 ring-primary ring-offset-1 ring-offset-background border-primary' : 'border-border/60 opacity-60 hover:opacity-100'"
                @click="result = res"
              >
                <ResultBadge :result="res" class="pointer-events-none" />
              </button>
            </div>
          </div>

          <div>
            <label class="block text-xs font-medium text-muted-foreground mb-1">所要時間 (分)</label>
            <UInput v-model="timeMinutes" type="number" placeholder="例: 20" min="0" size="sm" class="font-mono" />
          </div>

          <div class="sm:col-span-2">
            <label class="block text-xs font-medium text-muted-foreground mb-1">解答日時</label>
            <UInput v-model="solvedAt" type="datetime-local" size="sm" class="font-mono" />
          </div>
        </div>

        <!-- Tags -->
        <div>
          <label class="block text-xs font-medium text-muted-foreground mb-1.5 flex items-center justify-between">
            <span class="flex items-center gap-1"><UIcon name="i-lucide-tag" class="w-3.5 h-3.5" /> タグ / アルゴリズム</span>
            <span class="text-[11px] text-muted-foreground">Enterで追加</span>
          </label>
          <div class="flex gap-2">
            <UInput
              v-model="tagInput"
              placeholder="例: 累積和, 二分探索, DP..."
              size="sm"
              class="flex-1"
              @keydown.enter.prevent="addTag"
            />
            <UButton
              color="gray"
              variant="solid"
              size="sm"
              icon="i-lucide-plus"
              label="追加"
              @click="addTag"
            />
          </div>

          <!-- Selected Tags -->
          <div v-if="tags.length > 0" class="flex flex-wrap gap-1.5 mt-2">
            <UBadge
              v-for="tag in tags"
              :key="tag"
              color="gray"
              variant="subtle"
              size="sm"
              class="gap-1 pr-1"
            >
              <span>#{{ tag }}</span>
              <button type="button" class="hover:text-rose-400 font-bold ml-1 text-xs cursor-pointer" @click="removeTag(tag)">×</button>
            </UBadge>
          </div>

          <!-- Suggested Existing Tags -->
          <div v-if="existingTags && existingTags.length > 0" class="flex flex-wrap items-center gap-1 mt-2 text-[11px] text-muted-foreground">
            <span>よく使うタグ:</span>
            <button
              v-for="tag in existingTags.slice(0, 8)"
              :key="tag"
              type="button"
              class="hover:text-primary hover:underline px-1 py-0.5 rounded hover:bg-muted/50 cursor-pointer"
              @click="selectExistingTag(tag)"
            >
              +{{ tag }}
            </button>
          </div>
        </div>

        <!-- Review Needed Checkbox -->
        <div class="flex items-center gap-2 p-2.5 rounded-lg border border-border/70 bg-muted/20">
          <UCheckbox
            v-model="reviewNeeded"
            name="reviewNeeded"
            label="この問題を「要復習」に指定する"
          />
        </div>

        <!-- Memo -->
        <div>
          <label class="block text-xs font-medium text-muted-foreground mb-1">反省点・解法メモ</label>
          <UTextarea
            v-model="memo"
            placeholder="つまずいたポイント、境界値の処理、計算量の見積もり、解説を見て気付いた点など..."
            :rows="3"
            size="sm"
          />
        </div>
      </form>

      <template #footer>
        <div class="flex justify-end gap-2">
          <UButton color="gray" variant="ghost" @click="isOpen = false">キャンセル</UButton>
          <UButton
            form="record-form"
            type="submit"
            :color="isDuplicate ? 'amber' : 'primary'"
            :loading="isSubmitting"
          >
            {{ isEdit ? '更新する' : (isDuplicate ? '上書き更新して保存' : '記録を保存') }}
          </UButton>
        </div>
      </template>
    </UCard>
  </UModal>
</template>
